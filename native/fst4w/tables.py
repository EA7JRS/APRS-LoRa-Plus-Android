# Writes ldpc_240_74.h from the WSJT-X sources: tables.py <wsjtx-src>/lib/fst4 > ldpc_240_74.h
import re
import sys

d = sys.argv[1]
p = open(d + "/ldpc_240_74_parity.f90").read()


def block(name):
    m = re.search(r"data\s+" + name + r"\s*/(.*?)/", p, re.S)
    return [int(x) for x in re.findall(r"-?\d+", m.group(1))]


Mn, Nm, nrw = block("Mn"), block("Nm"), block("nrw")
assert len(Mn) == 240 * 3 and len(Nm) == 166 * 5 and len(nrw) == 166
g = re.findall(r'"([0-9a-f]{19})"', open(d + "/ldpc_240_74_generator.f90").read())
assert len(g) == 166
o = ["/* LDPC(240,74) code of FST4W, tables from WSJT-X 3.3.0-beta5 (lib/fst4/ldpc_240_74_parity.f90 and\n"
     " * ldpc_240_74_generator.f90; K1JT, K9AN; GPL-3.0). Generated by native/fst4w/tables.py. Indices are 1-based as in WSJT-X. */",
     "#pragma once",
     "static const short FST4_Mn[240][3] = {",
     ",\n".join("{%d,%d,%d}" % tuple(Mn[i * 3:i * 3 + 3]) for i in range(240)) + "};",
     "static const short FST4_Nm[166][5] = {",
     ",\n".join("{%d,%d,%d,%d,%d}" % tuple(Nm[i * 5:i * 5 + 5]) for i in range(166)) + "};",
     "static const unsigned char FST4_nrw[166] = {" + ",".join(map(str, nrw)) + "};",
     "/* generator: 166 parity rows, 19 hex digits each (74 message columns, the last digit holds 2 columns) */",
     "static const char *const FST4_GEN[166] = {",
     ",\n".join('"%s"' % s for s in g) + "};"]
print("\n".join(o))
